package com.mycompany.attendancemanagementsystem;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

public final class Database {
    private static final String URL = createDatabaseUrl();

    private Database() {
    }

    public static Connection getConnection() throws SQLException {
        return DriverManager.getConnection(URL, "sa", "");
    }

    public static void initialize() throws SQLException {
        try (Connection connection = getConnection();
             var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS employees (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        employee_code VARCHAR(24) UNIQUE,
                        full_name VARCHAR(120) NOT NULL,
                        department VARCHAR(120) NOT NULL,
                        email VARCHAR(180),
                        created_at TIMESTAMP NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS attendance (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        employee_id BIGINT NOT NULL,
                        event_type VARCHAR(3) NOT NULL,
                        recorded_at TIMESTAMP NOT NULL,
                        photo BLOB NOT NULL,
                        CONSTRAINT fk_attendance_employee
                            FOREIGN KEY (employee_id) REFERENCES employees(id)
                    )
                    """);
            statement.execute("""
                    CREATE INDEX IF NOT EXISTS idx_attendance_employee_time
                    ON attendance (employee_id, recorded_at)
                    """);
        }
    }

    private static String createDatabaseUrl() {
        String configuredPath = System.getenv("ATTENDANCE_DB_PATH");
        Path databasePath = configuredPath == null || configuredPath.isBlank()
                ? Path.of(System.getProperty("user.home"), ".attendance-management", "attendance")
                : Path.of(configuredPath).toAbsolutePath();
        Path parent = databasePath.getParent();
        if (parent != null) {
            try {
                Files.createDirectories(parent);
            } catch (IOException exception) {
                throw new ExceptionInInitializerError(exception);
            }
        }
        return "jdbc:h2:file:" + databasePath.toString().replace("\\", "/")
                + ";DB_CLOSE_ON_EXIT=FALSE";
    }
}
